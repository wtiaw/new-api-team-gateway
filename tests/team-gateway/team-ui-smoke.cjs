async function api(token, method, route, body) {
  const response = await fetch(base + route, { method, headers: { Authorization: 'Bearer ' + token, 'Content-Type': 'application/json' }, body: body ? JSON.stringify(body) : undefined });
  assert(response.headers.get('content-type')?.includes('json'), `Team API returned HTTP ${response.status}; preserve native rate limiting and retry after its window`);
  const result = await response.json();
  assert(response.ok && result.success, `${method} team API rejected`);
  return result.data;
}
async function signIn(page, username, password, target = '/teams') {
  await page.goto(base + '/sign-in?redirect=' + encodeURIComponent(target));
  await page.locator('input[name="username"]').fill(username);
  await page.locator('input[name="password"]').fill(password);
  const response = page.waitForResponse(r => r.request().method() === 'POST' && new URL(r.url()).pathname === '/api/user/login');
  await page.locator('button[type="submit"]').click();
  const signedIn = await response;
  assert(signedIn.ok(), `Native sign-in returned HTTP ${signedIn.status()}; preserve rate limiting`);
  const result = await signedIn.json();
  assert(result.success, 'Native sign-in failed');
  await page.waitForURL(url => !url.pathname.startsWith('/sign-in'));
  return result.data.access_token;
}
